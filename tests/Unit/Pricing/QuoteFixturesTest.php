/*
 * tests/fixtures/quotes.json is generated by tests/fixtures/generate_quotes.py, an independent
 * reference implementation of TECHNICAL_PLAN §10. Gate G3 adds the client's spreadsheet cases.
 */

function quoteFixture(): array
{
    static $fixture;

    return $fixture ??= json_decode((string) file_get_contents(dirname(__DIR__, 2).'/fixtures/quotes.json'), true, flags: JSON_THROW_ON_ERROR);
}

function fixtureMinor(?string $major): ?int
{
    return $major === null ? null : Money::fromMajor($major)->minor;
}

/**
 * @param  array<string, mixed>  $case
 */
function fixtureContext(array $case): QuoteContext
{
    $fixture = quoteFixture();
    $s = [...$fixture['_meta']['defaults']['settings'], ...($case['settings'] ?? [])];
    $margin = Decimal::round(Decimal::of($case['margin'] ?? $fixture['_meta']['defaults']['margin']), 2);

    $rates = [];
    foreach ($case['fx'] ?? $fixture['_meta']['defaults']['fx'] as $code => $rate) {
        $rates[$code] = new ResolvedRate($code, Decimal::round(Decimal::of($rate), 6), $margin, FxRateSource::Api, CarbonImmutable::now(), false);
    }

    $charges = [];
    foreach ([...($case['charges'] ?? $fixture['charges']), ...($case['extra_charges'] ?? [])] as $i => $row) {
        $charge = new Charge([
            'code' => $row['code'],
            'name' => $row['name'],
            'basis' => ChargeBasis::from($row['basis']),
            'amount_minor' => $row['amount'] === null ? null : Money::fromMajor($row['amount'])->minor,
            'currency_code' => $row['currency'],
            'payable_at' => ChargePayableAt::from($row['payable_at']),
            'applies' => ChargeApplies::from($row['applies']),
            'is_active' => $row['is_active'],
        ]);
        $charge->sort_order = $i;
        $charges[] = $charge;
    }

    $bands = array_map(fn (array $row) => new DepositBand([...$row, 'is_active' => true]), $fixture['bands']);

    return new QuoteContext(
        new QuoteSettings(
            reservationPercentBp: $s['reservation_percent_bp'],
            reservationRounding: RoundingMode::from($s['reservation_rounding']),
            dayCounting: DayCountingStrategy::from($s['day_counting']),
            windowStart: $s['daytime_window_start'],
            windowEnd: $s['daytime_window_end'],
            graceMinutes: $s['rolling_grace_minutes'],
            defaultMileageKm: $s['default_mileage_km'],
            unlimitedMileageAfterDays: $s['unlimited_mileage_after_days'],
            timezone: $fixture['_meta']['defaults']['timezone'],
        ),
        new FxTable('KES', $rates),
        $charges,
        $bands,
    );
}

/**
 * @param  array<string, mixed>  $case
 */
function fixtureInput(array $case): QuoteInput
{
    $fixture = quoteFixture();
    $car = $case['car'] ?? $fixture['_meta']['defaults']['car'];
    $zone = null;

    if (isset($case['zone'])) {
        $row = collect($fixture['zones'])->firstWhere('name', $case['zone']);
        $zone = new DeliveryZone(['name' => $row['name'], 'fee_minor' => fixtureMinor($row['fee'])]);
    }

    return new QuoteInput(
        carName: $car['name'],
        dailyRateMinor: fixtureMinor($car['daily_rate']),
        carValueMinor: fixtureMinor($car['value']),
        mileageLimitKm: $car['mileage_limit_km'],
        pickup: CarbonImmutable::parse($case['pickup']),
        return: CarbonImmutable::parse($case['return']),
        extras: $case['extras'] ?? [],
        zone: $zone,
        driverDob: isset($case['dob']) ? CarbonImmutable::parse($case['dob']) : null,
    );
}

it('has at least 40 cases, starting with the PRD worked example', function () {
    $cases = quoteFixture()['cases'];

    expect(count($cases))->toBeGreaterThanOrEqual(40)
        ->and($cases[0]['expect'])->toMatchArray(['total' => '66350.00', 'reservation' => '16588.00', 'balance' => '49762.00', 'deposit' => '160000.00']);
});

it('matches the reference quote', function (array $case) {
    $expect = $case['expect'];

    if (isset($expect['error'])) {
        $exception = match ($expect['error']) {
            'missing_fx' => MissingFxRateException::class,
            default => QuoteException::class,
        };

        expect(fn () => (new QuoteCalculator)->calculate(fixtureInput($case), fixtureContext($case)))->toThrow($exception);

        return;
    }

    $quote = (new QuoteCalculator)->calculate(fixtureInput($case), fixtureContext($case));
    $major = fn (?Money $money) => $money?->toMajorString();

    expect($quote->days)->toBe($expect['days'])
        ->and($major($quote->total))->toBe($expect['total'])
        ->and($major($quote->reservation))->toBe($expect['reservation'])
        ->and($major($quote->balance))->toBe($expect['balance'])
        ->and($major($quote->deposit))->toBe($expect['deposit'])
        ->and($quote->band?->percent_bp)->toBe($expect['deposit_percent_bp'])
        ->and($quote->driverAge)->toBe($expect['driver_age'])
        ->and($quote->mileageKmPerDay)->toBe($expect['mileage_km_per_day'])
        ->and($quote->requiresStaffQuote)->toBe($expect['requires_staff_quote'])
        ->and(array_map(fn (QuoteLine $line) => ['code' => $line->code, 'amount' => $major($line->amount), 'counted' => $line->counted], $quote->lines))
        ->toBe($expect['lines'])
        ->and(array_map(fn (array $amounts) => array_map($major, $amounts), $quote->display))
        ->toBe($expect['display']);
})->with(fn () => collect(quoteFixture()['cases'])->mapWithKeys(fn (array $case) => [$case['name'] => [$case]])->all());
