<?php

namespace App\Console\Commands;

use App\Enums\Permission;
use Illuminate\Console\Attributes\Description;
use Illuminate\Console\Attributes\Signature;
use Illuminate\Console\Command;
use Illuminate\Support\Facades\File;

#[Signature('permissions:types {--check : Fail if the file is out of date instead of writing it}')]
#[Description('Generate resources/js/types/permissions.ts from the Permission enum')]
class PermissionsTypesCommand extends Command
{
    public const PATH = 'resources/js/types/permissions.ts';

    public function handle(): int
    {
        $path = base_path(self::PATH);
        $contents = $this->render();

        if ($this->option('check')) {
            if (! File::exists($path) || File::get($path) !== $contents) {
                $this->components->error(self::PATH.' is out of date. Run `php artisan permissions:types`.');

                return self::FAILURE;
            }

            $this->components->info(self::PATH.' is up to date.');

            return self::SUCCESS;
        }

        File::put($path, $contents);
        $this->components->info('Wrote '.self::PATH.'.');

        return self::SUCCESS;
    }

    public function render(): string
    {
        $list = fn (array $values) => implode('', array_map(fn (string $value) => "    '{$value}',\n", $values));

        return <<<TS
        // Generated by `php artisan permissions:types` from app/Enums/Permission.php.
        // Do not edit by hand.

        export const permissions = [
        {$list(Permission::values())}] as const;

        export type Permission = (typeof permissions)[number];

        TS;
    }
}
